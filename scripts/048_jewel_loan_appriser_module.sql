
CREATE TABLE appraisal_master (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    appraisal_master_id BIGINT,
    appraisal_name VARCHAR(100),
    description VARCHAR(500),
    effective_from DATE,
    effective_to DATE,
    status VARCHAR(20), -- ACTIVE, INACTIVE
    created_by VARCHAR(100),
    created_date TIMESTAMP
);

CREATE TABLE appraisal_slab (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    appraisal_slab_id BIGINT ,
    appraisal_master_id BIGINT NOT NULL,

    loan_amount_from DECIMAL(18,2),
    loan_amount_to DECIMAL(18,2),

    charge_type VARCHAR(20), -- FIXED / PERCENTAGE

    charge_value DECIMAL(18,4),

    minimum_charge DECIMAL(18,2),
    maximum_charge DECIMAL(18,2),

    status VARCHAR(20),

    created_by VARCHAR(100),
    created_date TIMESTAMP,

    FOREIGN KEY (appraisal_master_id)
        REFERENCES appraisal_master(appraisal_master_id)
);


